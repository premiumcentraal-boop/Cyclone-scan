"""Generate attestation_vectors.json from the server's attestation verifier.

The scanner's on-device ChainVerifier (android/scanner .../attest/ChainVerifier.kt)
must reach the same chain-form, validity, security-level and placement
outcomes on these public Google fixtures; both test suites load this file.
Regenerate after changing verifier logic:

    python testvectors/generate_attestation_vectors.py
"""

from __future__ import annotations

import base64
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT.parent / "service"))

from cryptography import x509  # noqa: E402
from cryptography.hazmat.primitives.serialization import Encoding  # noqa: E402

from device_trust import reasons as R  # noqa: E402
from device_trust.attestation import AttestationVerifier  # noqa: E402
from device_trust.policy import TrustPolicy  # noqa: E402
from device_trust.revocation import RevocationList  # noqa: E402
from device_trust.roots import RootStore  # noqa: E402

FIXTURES = ROOT.parent / "service" / "tests" / "fixtures" / "real"
# Public Google fixtures that are also bundled with the scanner's JVM tests.
NAMES = [
    "akita_sdk34_TEE_EC_NONE", "akita_sdk34_TEE_RSA_NONE_USERAUTH", "caiman_sdk36_SB_EC_RKP",
    "caiman_sdk36_TEE_EC_RKP", "frankel_sdk37_TEE_EC_2026", "marlin_sdk29_TEE_EC_NONE",
    "sony-xperia10-iii_sdk33_TEE_EC",
]
TODAY = datetime(2026, 10, 14, tzinfo=timezone.utc)
ID_FIELDS = ("brand", "device", "product", "manufacturer", "model")


def case(name: str, when: str) -> dict:
    certs = x509.load_pem_x509_certificates((FIXTURES / f"{name}.pem").read_bytes())
    exp = json.loads((FIXTURES / f"{name}.json").read_text(encoding="utf-8"))
    app = exp["softwareEnforced"]["attestationApplicationId"]
    hw = exp["hardwareEnforced"]
    reported = {f: hw["attestationId" + f.capitalize()] for f in ID_FIELDS if "attestationId" + f.capitalize() in hw}
    now = TODAY if when == "today" else max(c.not_valid_before_utc for c in certs[1:])
    policy = TrustPolicy(package_name=app["packages"][0]["name"],
                         signing_cert_sha256=frozenset(base64.b64decode(s).hex() for s in app["signatures"]),
                         max_os_patch_age_months=1000)
    result = AttestationVerifier(policy, RootStore.bundled_google(), RevocationList.static({})).verify(
        [c.public_bytes(Encoding.DER) for c in certs], base64.b64decode(exp["attestationChallenge"]), reported,
        now=now)
    reasons = set(result.reasons)
    return {
        "name": name,
        "when": when,
        "now_ms": int(now.timestamp() * 1000),
        "expected": {
            "root_untrusted": R.ROOT_UNTRUSTED in reasons,
            "chain_type": result.evidence.chain_type if result.evidence else None,
            "cert_expired": R.CERT_EXPIRED in reasons,
            "legacy_exempt": bool(result.evidence and result.evidence.legacy_validity_exemption),
            "security_mismatch": R.SECURITY_LEVEL_CHAIN_MISMATCH in reasons,
            "provisioning_misplaced": R.PROVISIONING_INFO_MISPLACED in reasons,
        },
    }


def build() -> dict:
    return {
        "_comment": "Generated by generate_attestation_vectors.py from the server verifier. Do not edit by hand.",
        "cases": [case(n, w) for n in NAMES for w in ("capture", "today")],
    }


def render() -> str:
    return json.dumps(build(), indent=1, sort_keys=True) + "\n"


if __name__ == "__main__":
    (ROOT / "attestation_vectors.json").write_text(render(), encoding="utf-8")
    print(f"wrote {len(build()['cases'])} cases")
